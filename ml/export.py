#!/usr/bin/env python3
"""Write the trained classifier into the firmware as plain C float weights.

Usage: export.py runs/model.keras runs/windows.npz

Writes:
  firmware/dance_node/src/model_weights.h    conv/dense weights of ml/train.py build()
  firmware/dance_node/src/selftest_vectors.h 20 windows + expected (class, conf)

The firmware runs the network with cnn.c (no TensorFlow Lite dependency), so the
layer order, kernel sizes and padding there must match build() in train.py.
tests/test_cnn_parity.py compiles cnn.c on the host and checks it against Keras.

--selftest: print idx,class,conf,us for the 20 vectors from Keras (us = 0), for
comparison with the firmware's `selftest` serial command.
"""
import argparse
from pathlib import Path

import numpy as np
import tensorflow as tf

from dt.protocol import N_CLASSES
from dt.windows import CHANNELS, SCALES, WIN_LEN

ROOT = Path(__file__).resolve().parent.parent
FW_SRC = ROOT / "firmware/dance_node/src"

CONV1_OUT, CONV2_OUT, KERNEL = 16, 32, 5


def c_floats(name: str, arr: np.ndarray) -> str:
    flat = ", ".join(f"{v:.8e}f" for v in arr.ravel())
    dims = "".join(f"[{d}]" for d in arr.shape)
    return f"static const float {name}{dims} = {{{flat}}};\n"


def write_weights(model: tf.keras.Model) -> None:
    convs = [l for l in model.layers if isinstance(l, tf.keras.layers.Conv1D)]
    dense = [l for l in model.layers if isinstance(l, tf.keras.layers.Dense)]
    assert len(convs) == 2 and len(dense) == 1, "architecture differs from train.py build()"
    w1, b1 = convs[0].get_weights()
    w2, b2 = convs[1].get_weights()
    w3, b3 = dense[0].get_weights()
    assert w1.shape == (KERNEL, len(CHANNELS), CONV1_OUT), w1.shape
    assert w2.shape == (KERNEL, CONV1_OUT, CONV2_OUT), w2.shape
    assert w3.shape == (CONV2_OUT, N_CLASSES), w3.shape

    scales = ", ".join(f"{s:.1f}f" for s in SCALES)
    text = (
        "// Generated by ml/export.py. Do not edit.\n#pragma once\n"
        f"#define MODEL_WIN_LEN {WIN_LEN}\n#define MODEL_CHANNELS {len(CHANNELS)}\n"
        f"#define MODEL_KERNEL {KERNEL}\n#define MODEL_CONV1_OUT {CONV1_OUT}\n"
        f"#define MODEL_CONV2_OUT {CONV2_OUT}\n#define MODEL_CLASSES {N_CLASSES}\n"
        f"#define MODEL_SCALES {{ {scales} }}  // int8 window scales, see dt/windows.py\n"
        + c_floats("MODEL_W1", w1) + c_floats("MODEL_B1", b1)
        + c_floats("MODEL_W2", w2) + c_floats("MODEL_B2", b2)
        + c_floats("MODEL_W3", w3) + c_floats("MODEL_B3", b3)
    )
    (FW_SRC / "model_weights.h").write_text(text)
    n = sum(a.size for a in (w1, b1, w2, b2, w3, b3))
    print(f"wrote {FW_SRC / 'model_weights.h'}: {n} params, {n * 4} bytes")


def predict(model: tf.keras.Model, x: np.ndarray) -> tuple[np.ndarray, np.ndarray]:
    p = model.predict(x, verbose=0)
    best = p.argmax(1)
    conf = np.rint(p[np.arange(len(p)), best] * 255).astype(int)
    return best, conf


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("model")
    ap.add_argument("npz")
    ap.add_argument("--selftest", action="store_true")
    a = ap.parse_args()

    d = np.load(a.npz)
    x = d["x"].astype(np.float32)
    model = tf.keras.models.load_model(a.model)

    vec_idx = np.linspace(0, len(x) - 1, 20).astype(int)
    cls, conf = predict(model, x[vec_idx])
    if a.selftest:
        for i in range(len(vec_idx)):
            print(f"{i},{cls[i]},{conf[i]},0")
        return

    write_weights(model)
    lines = ["// Generated by ml/export.py. Do not edit.", "#pragma once", "#include <stdint.h>",
             f"#define SELFTEST_N {len(vec_idx)}",
             f"static const int8_t selftest_x[SELFTEST_N][{WIN_LEN}][{len(CHANNELS)}] = {{"]
    for vi in vec_idx:
        rows = ", ".join("{" + ", ".join(str(int(v)) for v in r) + "}" for r in d["x"][vi])
        lines.append("  {" + rows + "},")
    lines.append("};")
    lines.append("static const uint8_t selftest_expect[SELFTEST_N][2] = {")
    for i in range(len(vec_idx)):
        lines.append(f"  {{{cls[i]}, {conf[i]}}},")
    lines.append("};")
    (FW_SRC / "selftest_vectors.h").write_text("\n".join(lines) + "\n")
    print("wrote", FW_SRC / "selftest_vectors.h")


if __name__ == "__main__":
    main()
